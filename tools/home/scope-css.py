"""Turns a standalone design's <style> block into client/src/pages/home-v2.css.

Usage: python3 tools/home/scope-css.py <design.html> <index.css> <Home.tsx>

- Every selector is prefixed with `.home-v2` so the design cannot leak into other pages.
- `:root`, `html` and `body` become `.home-v2` itself.
- A reset block then cancels, on the elements this page uses, every property the
  project's index.css sets on them, so only the design's own rules apply.
"""
import re
import sys

design_path, index_css_path, home_path = sys.argv[1:4]
OUT = "client/src/pages/home-v2.css"
S = ".home-v2"


def strip_comments(text):
    return re.sub(r"/\*.*?\*/", "", text, flags=re.S)


def parse(text):
    """Yield (selector, body) for every rule, descending into @media/@supports."""
    out, i = [], 0
    while True:
        j = text.find("{", i)
        if j < 0:
            break
        head = text[i:j].strip()
        depth, k = 1, j + 1
        while depth and k < len(text):
            if text[k] == "{":
                depth += 1
            elif text[k] == "}":
                depth -= 1
            k += 1
        body = text[j + 1 : k - 1]
        i = k
        if head.startswith(("@media", "@supports")):
            out += parse(body)
        elif head.startswith("@"):
            continue
        else:
            out.append((head, body))
    return out


def scope_selector(sel):
    sel = sel.strip()
    if sel in (":root", "html", "body"):
        return S
    if sel == "*":
        return S + " *"
    return f"{S} {sel}"


def decls(body):
    return [d.split(":")[0].strip() for d in body.split(";") if ":" in d and not d.strip().startswith("--")]


# 1) the design's own CSS, scoped
design_css = strip_comments(re.search(r"<style>(.*?)</style>", open(design_path, encoding="utf8").read(), re.S).group(1))
design_css = re.sub(r"@import url\([^)]*\);", "", design_css)
def render_scoped(text):
    """Scope every rule, keeping @media/@supports wrappers so breakpoints still apply."""
    out, i = [], 0
    while True:
        j = text.find("{", i)
        if j < 0:
            break
        head = text[i:j].strip()
        depth, k = 1, j + 1
        while depth and k < len(text):
            if text[k] == "{":
                depth += 1
            elif text[k] == "}":
                depth -= 1
            k += 1
        body = text[j + 1 : k - 1]
        i = k
        if head.startswith(("@media", "@supports")):
            out.append(f"{head} {{\n{render_scoped(body)}}}")
        elif head.startswith("@"):
            continue
        else:
            sels = ", ".join(scope_selector(x) for x in head.split(",") if x.strip())
            out.append(f"{sels} {{ {re.sub(r'\\s+', ' ', body).strip()} }}")
    return "\n".join(out) + "\n"


design_out = render_scoped(design_css)
# keep the design's own @keyframes (parse() skipped them)
design_out += "\n" + "\n".join(
    m.group(0) for m in re.finditer(r"@keyframes[^{]*\{(?:[^{}]*\{[^{}]*\})*[^{}]*\}", design_css)
)

# 2) classes and tags used by the page, to know which old rules to cancel
home = open(home_path, encoding="utf8").read()
classes, tags = set(), set()
for m in re.finditer(r'className=\{?[`"]([^"`]*)[`"]', home):
    classes.update(re.findall(r"[a-zA-Z][\w-]*", m.group(1)))
for m in re.finditer(r"`([^`]*)`", home):
    classes.update(re.findall(r"[a-zA-Z][\w-]+", m.group(1)))
tags.update(re.findall(r"<([a-z][a-z0-9]*)[\s>/]", home))

# 3) the project's index.css: which properties it sets on those elements
index_css = strip_comments(open(index_css_path, encoding="utf8").read())
props = {}
for head, body in parse(index_css):
    d = decls(body)
    for sel in head.split(","):
        sel = sel.strip()
        targets = [f".{c}" for c in re.findall(r"\.([a-zA-Z][\w-]*)", sel) if c in classes]
        last = re.split(r"\s+", sel)[-1] if sel else ""
        if not targets and last in tags:
            targets.append(last)
        for t in targets:
            props.setdefault(t, set()).update(d)

guard = ["/* Cancel the project's index.css on the elements this page uses. */"]
for t in sorted(props):
    names = sorted(p for p in props[t] if p)
    if names:
        guard.append(f"{S} {t} {{ " + "; ".join(f"{p}: revert" for p in names) + "; }")

header = "/* Homepage design, scoped under .home-v2. Generated by tools/home/scope-css.py. */\n"
open(OUT, "w", encoding="utf8").write(header + "\n".join(guard) + "\n\n" + design_out + "\n")
print(f"{OUT}: {len(guard)-1} guarded selectors, {design_out.count("{")} design blocks")

